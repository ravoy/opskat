import { readdirSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// These operations deliberately return nil on cancellation or absent selection.
const nullable = {
  system: [
    "PreviewTabbyConfig",
    "ImportTabbySelected",
    "PreviewSSHConfig",
    "ImportSSHConfigSelected",
    "PreviewWindTermConfig",
    "PreviewRDPFiles",
    "PreviewRDPExcel",
    "SelectImportFile",
    "ImportSSHKeyFile",
  ],
  ai: ["GetActiveAIProvider"],
  customtype: ["SelectImportTypeFile"],
};
const root = "bindings/github.com/octays/opskat/internal/app";
mkdirSync("clients", { recursive: true });
for (const domain of readdirSync(root, { withFileTypes: true })) {
  if (!domain.isDirectory()) continue;
  for (const file of readdirSync(join(root, domain.name))) {
    if (!file.endsWith(".ts") || file === "models.ts" || file === "index.ts") continue;
    const source = readFileSync(join(root, domain.name, file), "utf8");
    const methods = [...source.matchAll(/^export function (\w+)\(/gm)].map((match) => match[1]);
    if (!methods.length) continue;
    writeFileSync(
      `clients/${domain.name}.ts`,
      `// Generated by scripts/generate-clients.mjs. Do not edit.\n` +
        `import * as native from "@bindings/github.com/octays/opskat/internal/app/${domain.name}/${file.slice(0, -3)}";\n` +
        `import { createIPCClient } from "@/lib/ipcClient";\n` +
        `const client = createIPCClient(native, ${JSON.stringify(nullable[domain.name] ?? [])});\n` +
        `export const { ${methods.join(", ")} } = client;\n`
    );
  }
}
